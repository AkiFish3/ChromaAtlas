package com.akira.chromaatlas.fabric;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.fabricmc.loader.api.FabricLoader;
import net.fabricmc.loader.api.ModContainer;
import net.minecraft.block.Block;
import net.minecraft.block.BlockState;
import net.minecraft.registry.Registries;
import net.minecraft.util.Identifier;
import org.slf4j.Logger;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileSystem;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * M2 前置验证（C 档三条件）：服务端 / 客户端能否读 mod jar 内的 assets、
 * 自解析 {@code blockstate -> model parent 链 -> textures.particle} 是否可行、
 * 以及「解析 + 解码 + 求均值」的真实单块耗时。
 *
 * <p>只读，产物：{@code config/mapcolor_preflight.txt}
 */
public final class Preflight {

    private Preflight() {
    }

    private static final int MAX_BLOCKS = 300;
    private static final long TIME_BUDGET_NS = 25_000_000_000L; // 25s 上限，避免拖慢启动
    private static final int SAMPLE_STEP = 4;                   // 每 4 像素采一次

    private static final Map<String, FileSystem> FS_CACHE = new HashMap<>();
    private static final java.util.Set<String> FS_OWNED = new java.util.HashSet<>();

    public static void run(Logger log) {
        long t0 = System.nanoTime();
        List<String> out = new ArrayList<>();
        try {
            out.add("# ChromaAtlas M2 preflight  (generated by runtime probe)");
            out.add("# jvm=" + System.getProperty("java.version") + " os=" + System.getProperty("os.name"));
            out.add("");

            // ---------- P1: jar 内 assets 可读性 ----------
            int containers = 0, readable = 0, hasStates = 0;
            long p1t0 = System.nanoTime();
            List<String> p1lines = new ArrayList<>();
            for (ModContainer mc : FabricLoader.getInstance().getAllMods()) {
                containers++;
                String ns = mc.getMetadata().getId();
                try {
                    FileSystem fs = fs(ns, mc);
                    if (fs == null) {
                        p1lines.add(ns + "\tNO_ROOT");
                        continue;
                    }
                    readable++;
                    Path bs = fs.getPath("/assets/" + ns + "/blockstates");
                    if (Files.isDirectory(bs)) {
                        hasStates++;
                        p1lines.add(ns + "\tOK\tblockstates");
                    } else {
                        p1lines.add(ns + "\tOK\tno_blockstates");
                    }
                } catch (Throwable t) {
                    p1lines.add(ns + "\tERR\t" + t.getClass().getSimpleName());
                }
            }
            out.add("## P1 jar assets 可读性");
            out.add("containers=" + containers + " fs_open_ok=" + readable + " with_blockstates=" + hasStates
                    + " elapsed_ms=" + ms(p1t0));
            out.add("");

            // ---------- P2: blockstate -> model -> texture 解析 ----------
            long p2t0 = System.nanoTime();
            int tried = 0, okModel = 0, okTexture = 0, noState = 0, noModel = 0, noTex = 0, decodeFail = 0;
            int transparent = 0;
            int hasElements = 0;
            long parseNs = 0, decodeNs = 0;
            Map<String, long[]> texSeen = new LinkedHashMap<>(); // texId -> {count}
            List<String> samples = new ArrayList<>();
            List<String> failures = new ArrayList<>();

            for (Block block : Registries.BLOCK) {
                if (tried >= MAX_BLOCKS || (System.nanoTime() - p2t0) > TIME_BUDGET_NS) {
                    break;
                }
                Identifier id;
                try {
                    id = Registries.BLOCK.getId(block);
                    BlockState st = block.getDefaultState();
                    // ★第 32 轮 / R107★ 不再 st.getMapColor(null, null)（第三方 mixin 会用 world ⇒ NPE）
                    if (RawColors.color(st, block) != 0) {
                        continue; // 只关心本来没色的
                    }
                } catch (Throwable t) {
                    continue;
                }
                String ns = id.getNamespace();
                ModContainer mc = FabricLoader.getInstance().getModContainer(ns).orElse(null);
                if (mc == null) {
                    continue;
                }
                tried++;
                try {
                    FileSystem fs = fs(ns, mc);
                    if (fs == null) {
                        continue;
                    }
                    long lp = System.nanoTime();
                    Path bsPath = fs.getPath("/assets/" + ns + "/blockstates/" + id.getPath() + ".json");
                    if (!Files.isRegularFile(bsPath)) {
                        noState++;
                        continue;
                    }
                    String modelId = firstModel(safeJson(bsPath));
                    if (modelId == null) {
                        noModel++;
                        continue;
                    }
                    Chain chain = followParent(fs, modelId, 16);
                    parseNs += System.nanoTime() - lp;
                    if (chain == null) {
                        noModel++;
                        continue;
                    }
                    if (chain.hasElements) {
                        hasElements++;
                    }
                    okModel++;
                    String tex = chain.texture;
                    if (tex == null) {
                        noTex++;
                        continue;
                    }
                    okTexture++;
                    long[] seen = texSeen.get(tex);
                    if (seen != null) {
                        seen[0]++;
                        continue; // 同贴图已解过，去重
                    }
                    texSeen.put(tex, new long[]{1});

                    long ld = System.nanoTime();
                    int[] rgb = meanColor(fs, tex);
                    decodeNs += System.nanoTime() - ld;
                    if (rgb == null) {
                        decodeFail++;
                        continue;
                    }
                    if (rgb[0] < 0) {
                        transparent++;
                        continue;
                    }
                    if (samples.size() < 12) {
                        samples.add(id + "\t" + tex + "\t#" + String.format("%02X%02X%02X", rgb[1], rgb[2], rgb[3]));
                    }
                } catch (Throwable t) {
                    if (failures.size() < 10) {
                        failures.add(id + "\t" + t.getClass().getSimpleName() + ": " + t.getMessage());
                    }
                }
            }

            out.add("## P2 blockstate->model->texture 自解析");
            out.add("tried=" + tried + " model_resolved=" + okModel + " texture_resolved=" + okTexture
                    + " has_elements=" + hasElements);
            out.add("miss: no_state=" + noState + " no_model=" + noModel + " no_texture=" + noTex);
            out.add("textures_unique=" + texSeen.size() + " decode_fail=" + decodeFail + " fully_transparent=" + transparent);
            out.add("elapsed: parse_ms=" + ms(p2t0) + " of_which_json_ns=" + parseNs / 1_000_000L
                    + " decode_ns=" + decodeNs / 1_000_000L);
            if (!texSeen.isEmpty()) {
                out.add(String.format(java.util.Locale.ROOT,
                        "per_texture: parse=%.3fms decode=%.3fms",
                        (parseNs / 1_000_000.0) / tried,
                        (decodeNs / 1_000_000.0) / texSeen.size()));
            }
            out.add("");
            out.add("## samples");
            out.addAll(samples);
            if (!failures.isEmpty()) {
                out.add("");
                out.add("## failures(first 10)");
                out.addAll(failures);
            }

            Files.write(Probe.configDir().resolve("mapcolor_preflight.txt"), out, StandardCharsets.UTF_8);
            log.info("[ChromaAtlas/preflight] done in {}ms -> {}", ms(t0),
                    Probe.configDir().resolve("mapcolor_preflight.txt"));
            for (String l : out) {
                if (l.startsWith("containers=") || l.startsWith("tried=") || l.startsWith("miss:")
                        || l.startsWith("textures_unique=") || l.startsWith("per_texture:")) {
                    log.info("[ChromaAtlas/preflight] {}", l);
                }
            }
        } catch (Throwable t) {
            log.error("[ChromaAtlas/preflight] 失败（不影响游戏）", t);
        } finally {
            for (FileSystem fs : FS_CACHE.values()) {
                try {
                    fs.close();
                } catch (Exception ignored) {
                }
            }
            FS_CACHE.clear();
        }
    }

    // ---------------- helpers ----------------

    private static long ms(long sinceNs) {
        return (System.nanoTime() - sinceNs) / 1_000_000L;
    }

    private static FileSystem fs(String ns, ModContainer mc) throws Exception {
        FileSystem cached = FS_CACHE.get(ns);
        if (cached != null) {
            return cached;
        }
        List<Path> roots = mc.getRootPaths();
        if (roots.isEmpty()) {
            return null;
        }
        Path p = roots.get(0);
        FileSystem fs;
        if (Files.isDirectory(p)) {
            fs = p.getFileSystem();
        } else {
            fs = FileSystems.newFileSystem(p);
        }
        FS_CACHE.put(ns, fs);
        return fs;
    }

    private static JsonObject safeJson(Path p) {
        try (InputStream in = Files.newInputStream(p)) {
            JsonElement e = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            return e.isJsonObject() ? e.getAsJsonObject() : null;
        } catch (Exception e) {
            return null;
        }
    }

    /** blockstate -> 第一个 variants 值 或 multipart 第一个 apply 的 model。 */
    private static String firstModel(JsonObject bs) {
        if (bs == null) {
            return null;
        }
        if (bs.has("variants") && bs.get("variants").isJsonObject()) {
            for (Map.Entry<String, JsonElement> e : bs.getAsJsonObject("variants").entrySet()) {
                String m = modelOf(e.getValue());
                if (m != null) {
                    return m;
                }
            }
        }
        if (bs.has("multipart") && bs.get("multipart").isJsonArray()) {
            for (JsonElement el : bs.getAsJsonArray("multipart")) {
                if (el.isJsonObject() && el.getAsJsonObject().has("apply")) {
                    String m = modelOf(el.getAsJsonObject().get("apply"));
                    if (m != null) {
                        return m;
                    }
                }
            }
        }
        return null;
    }

    private static String modelOf(JsonElement el) {
        if (el == null) {
            return null;
        }
        if (el.isJsonArray()) {
            for (JsonElement e : el.getAsJsonArray()) {
                String m = modelOf(e);
                if (m != null) {
                    return m;
                }
            }
            return null;
        }
        if (el.isJsonObject() && el.getAsJsonObject().has("model")) {
            JsonElement m = el.getAsJsonObject().get("model");
            return m.isJsonPrimitive() ? m.getAsString() : null;
        }
        return null;
    }

    private static final class Chain {
        String texture;
        boolean hasElements;
    }

    /** 沿 parent 链向上找 textures.particle（退化为首个 texture）与 elements。 */
    private static Chain followParent(FileSystem defaultFs, String modelId, int maxDepth) {
        Chain c = new Chain();
        String cur = modelId;
        String firstTexture = null;
        for (int depth = 0; depth < maxDepth && cur != null; depth++) {
            String ns = "minecraft";
            String path = cur;
            int colon = cur.indexOf(':');
            if (colon >= 0) {
                ns = cur.substring(0, colon);
                path = cur.substring(colon + 1);
            }
            FileSystem fs = defaultFs;
            if (!"minecraft".equals(ns)) {
                ModContainer mc = FabricLoader.getInstance().getModContainer(ns).orElse(null);
                if (mc == null) {
                    return c.texture == null ? null : c;
                }
                try {
                    fs = fs(ns, mc);
                } catch (Exception e) {
                    return c.texture == null ? null : c;
                }
            }
            if (fs == null) {
                return c.texture == null ? null : c;
            }
            Path mp = fs.getPath("/assets/" + ns + "/models/" + path + ".json");
            if (!Files.isRegularFile(mp)) {
                // minecraft 的模型在游戏 jar 里，不在 mod 容器 -> 放弃该分支
                return c.texture == null ? null : c;
            }
            JsonObject o = safeJson(mp);
            if (o == null) {
                return c.texture == null ? null : c;
            }
            if (!c.hasElements && o.has("elements")) {
                c.hasElements = true;
            }
            if (o.has("textures") && o.get("textures").isJsonObject()) {
                JsonObject tx = o.getAsJsonObject("textures");
                if (c.texture == null && tx.has("particle")) {
                    c.texture = tx.get("particle").getAsString();
                }
                if (firstTexture == null && tx.size() > 0) {
                    for (Map.Entry<String, JsonElement> e : tx.entrySet()) {
                        String v = e.getValue().getAsString();
                        if (v.startsWith("#")) {
                            continue;
                        }
                        firstTexture = v;
                        break;
                    }
                }
            }
            cur = o.has("parent") ? o.get("parent").getAsString() : null;
            if (cur != null && cur.startsWith("builtin/")) {
                break;
            }
        }
        if (c.texture == null) {
            c.texture = firstTexture;
        }
        return (c.texture == null && !c.hasElements) ? null : c;
    }

    /** 返回 {ok, r, g, b}；全透明返回 {-1,0,0,0}；失败 null。 */
    private static int[] meanColor(FileSystem fs, String texId) {
        String ns = "minecraft";
        String path = texId;
        int colon = texId.indexOf(':');
        if (colon >= 0) {
            ns = texId.substring(0, colon);
            path = texId.substring(colon + 1);
        }
        Path png;
        try {
            if ("minecraft".equals(ns)) {
                return null; // vanilla 贴图不在 mod 容器，跳过（不算失败）
            }
            ModContainer mc = FabricLoader.getInstance().getModContainer(ns).orElse(null);
            if (mc == null) {
                return null;
            }
            FileSystem tfs = fs(ns, mc);
            if (tfs == null) {
                return null;
            }
            png = tfs.getPath("/assets/" + ns + "/textures/" + path + ".png");
        } catch (Exception e) {
            return null;
        }
        try (InputStream in = Files.newInputStream(png)) {
            BufferedImage img = ImageIO.read(in);
            if (img == null) {
                return null;
            }
            long r = 0, g = 0, b = 0, n = 0;
            for (int y = 0; y < img.getHeight(); y += SAMPLE_STEP) {
                for (int x = 0; x < img.getWidth(); x += SAMPLE_STEP) {
                    int argb = img.getRGB(x, y);
                    int a = (argb >>> 24) & 0xFF;
                    if (a < 16) {
                        continue;
                    }
                    r += (argb >> 16) & 0xFF;
                    g += (argb >> 8) & 0xFF;
                    b += argb & 0xFF;
                    n++;
                }
            }
            if (n == 0) {
                return new int[]{-1, 0, 0, 0};
            }
            return new int[]{1, (int) (r / n), (int) (g / n), (int) (b / n)};
        } catch (Exception e) {
            return null;
        }
    }
}
